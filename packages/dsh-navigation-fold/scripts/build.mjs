import { mkdir, writeFile } from 'node:fs/promises';
import { installNavigationFold } from '../src/navigation-fold.js';

// Native ModuleLoader format; no bundler or external browser dependency is needed.
const output = `// Generated by scripts/build.mjs; edit src/navigation-fold.js instead.\nwindow.__ModuleLoader__.load({
  id: 'dsh-navigation-fold',
  factory: () => {
    const installNavigationFold = ${installNavigationFold.toString()};
    return {
      name: 'dsh-navigation-fold',
      apply(ctx) {
        ctx.effect(() => installNavigationFold(document));
      },
    };
  },
});\n`;
const directory = new URL('../lib/', import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(new URL('client.js', directory), output, 'utf8');
console.log('Built lib/client.js (zero runtime dependencies).');
